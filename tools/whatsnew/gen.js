// The app's What's new: web/changelog.json at the pinned upstream commit (UPSTREAM) as the two files the app reads.
//
//   app/SupportFins/Resources/changelog.json   { version, releases: [{ version, tag, date, lines }] }, newest release
//                                              first, `lines` as the landing card lists them (web/changelog.js)
//   app/Version.xcconfig                       MARKETING_VERSION, the app's version (app/project.yml: configFiles)
//
// The logic is the web's own: this imports web/changelog.js from the checkout (releases, the card's lines, nextVersion)
// instead of copying it. Released entries only: an entry waits in `unreleased` until the release step stamps it, so the
// card (and so the app) never shows a version no release made. The app's version is the newest release's; until the
// first one exists it is the version that release will take (nextVersion: 1.0.0).
//
//   deno run -A tools/whatsnew/gen.js           write both files
//   deno run -A tools/whatsnew/gen.js --check   fail when either differs (in `just gate`)
import { UPSTREAM_ROOT } from "../../parity/oracle/lib/pin.js";

const WEB = `${UPSTREAM_ROOT}/web`;
const { CHECKS, VERSION_RE, releases, nextVersion, isNewer, cardHTML } = await import(`${WEB}/changelog.js`);
const data = JSON.parse(Deno.readTextFileSync(`${WEB}/changelog.json`));

// tests/changelog.test.js's "entries are well formed, releases run oldest first with rising versions"
function wellFormed(e, at) {
  const fail = (m) => { throw new Error(`web/changelog.json: ${at}: ${m}`); };
  if (!(e.pr === undefined || (Number.isInteger(e.pr) && e.pr > 0))) fail("pr is optional, a positive integer");
  if (!(/^\d{4}-\d{2}-\d{2}$/.test(e.date) && !isNaN(Date.parse(e.date)))) fail("date");
  if (!(typeof e.text === "string" && e.text.length > 0 && e.text.length <= 240 && !e.text.includes("\n"))) fail("one short line");
  if (!CHECKS.includes(e.check)) fail(`check ${e.check}`);
  for (const h of e.highlights ?? []) {
    if (!(typeof h.text === "string" && h.text.length > 0 && h.text.length <= 160 && !h.text.includes("\n"))) fail("a highlight is one short line");
    if (!(h.prs === undefined || (Array.isArray(h.prs) && h.prs.every((n) => Number.isInteger(n) && n > 0)))) fail("highlight prs");
  }
}
if (!Array.isArray(data.releases) || !Array.isArray(data.unreleased)) throw new Error("web/changelog.json: releases and unreleased are arrays");
data.releases.forEach((r, i) => {
  if (!VERSION_RE.test(r.version)) throw new Error(`release ${i}: version ${r.version}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date)) throw new Error(`v${r.version}: date`);
  if (!Array.isArray(r.entries) || !r.entries.length) throw new Error(`v${r.version}: entries`);
  if (i && !isNewer({ releases: data.releases.slice(0, i) }, r.version)) throw new Error(`v${r.version} comes after the release before it`);
});
const all = [...data.releases.flatMap((r) => r.entries), ...data.unreleased];
all.forEach((e, i) => wellFormed(e, `entry ${i}`));
for (let i = 1; i < all.length; i++) if (all[i].date < all[i - 1].date) throw new Error(`web/changelog.json: entry ${i}: dates run oldest first`);

// web/changelog.js `lines`: the newest entry first, an entry's highlights standing in for its text
const lines = (r) => [...r.entries].reverse().flatMap((e) => (e.highlights?.length ? e.highlights.map((h) => h.text) : [e.text]));
const shown = releases(data);
// the lines are what the page's card lists, in its order: compare with the card the web itself writes
{
  const esc = (t) => String(t).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const card = [...cardHTML(data).matchAll(/<li>(.*?)<\/li>/g)].map((m) => m[1]);
  const mine = shown.flatMap((r) => lines(r)).map(esc);
  if (JSON.stringify(card) !== JSON.stringify(mine)) throw new Error("whatsnew: the lines differ from the card web/changelog.js writes");
}
const version = shown[0]?.version ?? nextVersion(data);
const json = JSON.stringify({
  version,
  releases: shown.map((r) => ({ version: r.version, tag: r.tag, date: r.date, lines: lines(r) })),
}, null, 2) + "\n";
const xcconfig = `// Generated by tools/whatsnew/gen.js from web/changelog.json at the pinned upstream commit. Do not edit.\nMARKETING_VERSION = ${version}\n`;

const root = new URL("../../", import.meta.url);
const files = [["app/SupportFins/Resources/changelog.json", json], ["app/Version.xcconfig", xcconfig]];
if (Deno.args.includes("--check")) {
  const stale = files.filter(([f, text]) => { try { return Deno.readTextFileSync(new URL(f, root)) !== text; } catch { return true; } });
  if (stale.length) { console.error(`whatsnew: ${stale.map(([f]) => f).join(", ")} out of date: run just whatsnew-gen`); Deno.exit(1); }
  console.log(`whatsnew: up to date (v${version}, ${shown.length} released)`);
} else {
  for (const [f, text] of files) Deno.writeTextFileSync(new URL(f, root), text);
  console.log(`whatsnew: wrote v${version} (${shown.length} released)`);
}
