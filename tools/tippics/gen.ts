// Generates app/SupportFins/Features/Tips/TipPictures.generated.swift from the web's pictures (web/ui/tippics.js in the
// pinned JS checkout): each setting's tip card has a 240 x 130 diagram, a string of SVG there and a list of
// primitives here. `--check` fails when the file differs (part of `just gate`). Re-run at the upstream catch-up.
import { WEB_ROOT } from "../i18n/web.ts";

const OUT = new URL("../../app/SupportFins/Features/Tips/TipPictures.generated.swift", import.meta.url).pathname;
const { TIP_PICS } = await import(`file://${WEB_ROOT}/ui/tippics.js`) as { TIP_PICS: Record<string, string> };

const num = (s: string | undefined) => (s === undefined ? "0" : String(Number(s)));
const q = (s: string) => JSON.stringify(s);

function prims(svg: string): string[] {
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  const out: string[] = [];
  for (const m of body.matchAll(/<(rect|line|path|circle|ellipse)\s([^>]*?)\/>/g)) {
    const a: Record<string, string> = {};
    for (const x of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) a[x[1]] = x[2];
    const cls = q(a.class ?? "");
    const none = a.fill === "none" ? ", noFill: true" : "";
    switch (m[1]) {
      case "rect": out.push(`.rect(${cls}, ${num(a.x)}, ${num(a.y)}, ${num(a.width)}, ${num(a.height)}, rx: ${num(a.rx)}${none})`); break;
      case "line": out.push(`.line(${cls}, ${num(a.x1)}, ${num(a.y1)}, ${num(a.x2)}, ${num(a.y2)})`); break;
      case "path": out.push(`.path(${cls}, ${q(a.d)}${none})`); break;
      case "circle": out.push(`.ellipse(${cls}, ${num(a.cx)}, ${num(a.cy)}, ${num(a.r)}, ${num(a.r)}${none})`); break;
      case "ellipse": out.push(`.ellipse(${cls}, ${num(a.cx)}, ${num(a.cy)}, ${num(a.rx)}, ${num(a.ry)}${none})`); break;
    }
  }
  // every element must have been read: a primitive this does not know would draw nothing
  const tags = [...body.matchAll(/<(\w+)/g)].length;
  if (tags !== out.length) throw new Error(`tippics: ${tags} elements, ${out.length} read in ${svg.slice(0, 80)}`);
  return out;
}

let text = `// GENERATED by tools/tippics/gen.ts from web/ui/tippics.js (\`just tippics-gen\`): do not edit.
// The web's tip-card pictures as drawing primitives, 240 x 130, the plate along y = 118. \`TipPicture\` draws them.

extension TipPictures {
    static let all: [String: [TipPrim]] = [
`;
for (const key of Object.keys(TIP_PICS)) {
  text += `        ${q(key)}: [\n${prims(TIP_PICS[key]).map((p) => `            ${p},`).join("\n")}\n        ],\n`;
}
text += "    ]\n}\n";

if (Deno.args.includes("--check")) {
  let disk = "";
  try { disk = Deno.readTextFileSync(OUT); } catch { /* missing */ }
  if (disk !== text) { console.error("tippics: TipPictures.generated.swift is out of date with web/ui/tippics.js; run `just tippics-gen`"); Deno.exit(1); }
  console.log(`tippics: current (${Object.keys(TIP_PICS).length} pictures)`);
} else {
  Deno.writeTextFileSync(OUT, text);
  console.log(`tippics: wrote ${Object.keys(TIP_PICS).length} pictures`);
}
